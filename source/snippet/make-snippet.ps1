<#
  Builds claude-rtl-snippet.js from the "Claude Arabic RTL Fix" browser extension:
  content.js (verbatim) + styles.css, wrapped so it can run as a DevTools snippet.
  Picks the highest-numbered "vN ..." folder unless -ExtensionDir is given.
  If the extension folder is not available, the existing script is kept.
  ASCII-only on purpose: Windows PowerShell 5.1 reads BOM-less scripts as ANSI.
#>
param(
  [string]$ExtensionDir,
  [string]$ProjectRoot = (Join-Path $PSScriptRoot '..\..\..\Claude Arabic RTL Fix'),
  [string]$OutFile = (Join-Path $PSScriptRoot 'claude-rtl-snippet.js')
)

$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding($false)

if (-not $ExtensionDir) {
  if (-not (Test-Path -LiteralPath $ProjectRoot)) {
    Write-Warning "Extension folder not found ($ProjectRoot) - keeping the existing snippet."
    return
  }
  $versions = Get-ChildItem -LiteralPath $ProjectRoot -Directory |
    Where-Object { $_.Name -match '^v(\d+)' } |
    Sort-Object { [int]([regex]::Match($_.Name, '^v(\d+)').Groups[1].Value) } -Descending
  foreach ($v in $versions) {
    $hit = Get-ChildItem -LiteralPath $v.FullName -Recurse -Filter 'content.js' | Select-Object -First 1
    if ($hit) { $ExtensionDir = $hit.DirectoryName; break }
  }
  if (-not $ExtensionDir) { throw "No content.js found under any 'vN' folder in $ProjectRoot" }
}

$content = [IO.File]::ReadAllText((Join-Path $ExtensionDir 'content.js'), $utf8).Replace("`r`n", "`n")
$styles  = [IO.File]::ReadAllText((Join-Path $ExtensionDir 'styles.css'), $utf8).Replace("`r`n", "`n")
$version = 'unknown'
$manifest = Join-Path $ExtensionDir 'manifest.json'
if (Test-Path -LiteralPath $manifest) { $version = ([IO.File]::ReadAllText($manifest, $utf8) | ConvertFrom-Json).version }

$stylesJs = $styles.Replace('\', '\\').Replace('`', '\`').Replace('${', '\${')
$source = Split-Path -Leaf (Split-Path -Parent $ExtensionDir)

$head = @"
// Claude Arabic RTL Fix - Claude Desktop build, extension $version ("$source").
// Generated by make-snippet.ps1. Do not edit - change the extension and rebuild.
(() => {
  if (window.__claudeArabicRtlFix) return;
  window.__claudeArabicRtlFix = '$version';

  const adoptCss = (css) => {
    try {
      const sheet = new CSSStyleSheet();
      sheet.replaceSync(css);
      document.adoptedStyleSheets = [...document.adoptedStyleSheets, sheet];
    } catch (e) {
      const style = document.createElement('style');
      style.textContent = css;
      document.head.appendChild(style);
    }
  };

  adoptCss(``
"@

$mid = @"
``);

"@

$tail = @"


  const adoptOwnStyle = () => {
    const own = document.getElementById('claude-rtl-style');
    if (!own) return false;
    if (!own.sheet) adoptCss(own.textContent);
    return true;
  };
  if (!adoptOwnStyle()) setTimeout(adoptOwnStyle, 500);
})();
"@

$out = ($head + $stylesJs + $mid + $content + $tail).Replace("`r`n", "`n")
[IO.File]::WriteAllText($OutFile, $out, $utf8)
Write-Host "Snippet built from extension $version ($source)"
